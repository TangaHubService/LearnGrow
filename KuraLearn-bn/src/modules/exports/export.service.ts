interface ExportColumn {
  header: string;
  key: string;
}

function escapeCSV(value: unknown): string {
  const str = String(value ?? "");
  if (str.includes(",") || str.includes('"') || str.includes("\n")) {
    return `"${str.replace(/"/g, '""')}"`;
  }
  return str;
}

export function generateCSV(columns: ExportColumn[], rows: Record<string, unknown>[]): string {
  const header = columns.map((c) => escapeCSV(c.header)).join(",");
  const body = rows.map((row) =>
    columns.map((c) => escapeCSV(row[c.key])).join(",")
  ).join("\n");
  return `${header}\n${body}`;
}

export function generateExcelXML(columns: ExportColumn[], rows: Record<string, unknown>[]): string {
  const header = columns.map((c) => `<Cell><Data ss:Type="String">${escapeXML(c.header)}</Data></Cell>`).join("");
  const body = rows.map((row) =>
    `<Row>${columns.map((c) => {
      const val = row[c.key];
      const type = typeof val === "number" ? "Number" : "String";
      return `<Cell><Data ss:Type="${type}">${escapeXML(String(val ?? ""))}</Data></Cell>`;
    }).join("")}</Row>`
  ).join("\n");

  return `<?xml version="1.0" encoding="UTF-8"?>
<?mso-application progid="Excel.Sheet"?>
<Workbook xmlns="urn:schemas-microsoft-com:office:spreadsheet"
  xmlns:ss="urn:schemas-microsoft-com:office:spreadsheet">
  <Worksheet ss:Name="Export">
    <Table>
      <Row>${header}</Row>
      ${body}
    </Table>
  </Worksheet>
</Workbook>`;
}

function escapeXML(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
}

export function generatePDFHtml(title: string, columns: ExportColumn[], rows: Record<string, unknown>[]): string {
  const headerRow = columns.map((c) => `<th style="text-align:left;padding:8px 12px;border-bottom:2px solid #e2e8f0;font-weight:600;color:#475569;">${escapeXML(c.header)}</th>`).join("");
  const bodyRows = rows.map((row, i) =>
    `<tr${i % 2 === 0 ? ' style="background:#f8fafc;"' : ""}>${columns.map((c) =>
      `<td style="padding:8px 12px;border-bottom:1px solid #e2e8f0;color:#334155;">${escapeXML(String(row[c.key] ?? ""))}</td>`
    ).join("")}</tr>`
  ).join("\n");

  return `<!DOCTYPE html>
<html><head><meta charset="utf-8"><title>${escapeXML(title)}</title>
<style>body{font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif;padding:40px;color:#1e293b;}
h1{font-size:20px;margin-bottom:24px;color:#0f172a;}
table{width:100%;border-collapse:collapse;font-size:13px;}
</style></head><body>
<h1>${escapeXML(title)}</h1>
<table><thead><tr>${headerRow}</tr></thead>
<tbody>${bodyRows}</tbody></table>
<p style="margin-top:24px;font-size:11px;color:#94a3b8;">Generated by KuraLearn</p>
</body></html>`;
}

export async function logExport(
  schoolId: string,
  userId: string,
  format: string,
  entityType: string,
  filters?: Record<string, unknown>,
) {
  await prisma.auditLog.create({
    data: {
      schoolId,
      userId,
      action: `EXPORT_${format.toUpperCase()}`,
      entityType,
      metadata: { format, filters } as any,
    },
  });
}

export async function exportAttendance(schoolId: string, classId?: string, startDate?: string, endDate?: string) {
  const where: any = { schoolId };
  if (classId) where.classId = classId;
  if (startDate) where.date = { ...(where.date || {}), gte: new Date(startDate) };
  if (endDate) where.date = { ...(where.date || {}), lte: new Date(endDate) };

  const records = await prisma.attendanceRecord.findMany({
    where,
    include: {
      student: { include: { user: { select: { name: true } } } },
      class: { select: { name: true } },
    },
    orderBy: { date: "asc" },
  });

  const columns: ExportColumn[] = [
    { header: "Student Name", key: "studentName" },
    { header: "Class", key: "className" },
    { header: "Date", key: "date" },
    { header: "Status", key: "status" },
  ];

  const rows = records.map((r) => ({
    studentName: r.student?.user?.name ?? "Unknown",
    className: r.class?.name ?? "Unknown",
    date: r.date.toISOString().split("T")[0],
    status: r.status,
  }));

  return { columns, rows };
}

export async function exportMarks(schoolId: string, classId?: string, subjectId?: string, termId?: string) {
  const where: any = { schoolId };
  if (classId) where.classId = classId;
  if (subjectId) where.subjectId = subjectId;
  if (termId) where.termId = termId;

  const marks = await prisma.mark.findMany({
    where,
    include: {
      student: { include: { user: { select: { name: true } } } },
      subject: { select: { name: true } },
      class: { select: { name: true } },
    },
    orderBy: [{ classId: "asc" }, { student: { user: { name: "asc" } } }],
  });

  const columns: ExportColumn[] = [
    { header: "Student Name", key: "studentName" },
    { header: "Class", key: "className" },
    { header: "Subject", key: "subjectName" },
    { header: "Assessment", key: "assessmentType" },
    { header: "Score", key: "score" },
    { header: "Max Score", key: "maxScore" },
    { header: "Percentage", key: "percentage" },
    { header: "Grade", key: "grade" },
  ];

  const rows = marks.map((m) => ({
    studentName: m.student?.user?.name ?? "Unknown",
    className: m.class?.name ?? "Unknown",
    subjectName: m.subject?.name ?? "Unknown",
    assessmentType: m.assessmentType,
    score: m.score ?? "—",
    maxScore: m.maxScore,
    percentage: m.percentage != null ? `${m.percentage.toFixed(1)}%` : "—",
    grade: m.grade ?? "—",
  }));

  return { columns, rows };
}

export async function exportStudents(schoolId: string, classId?: string) {
  const where: any = { schoolId };
  if (classId) where.classId = classId;

  const students = await prisma.student.findMany({
    where,
    include: {
      user: { select: { name: true, email: true } },
      class: { select: { name: true } },
      level: { select: { name: true } },
    },
    orderBy: { user: { name: "asc" } },
  });

  const columns: ExportColumn[] = [
    { header: "Name", key: "name" },
    { header: "Email", key: "email" },
    { header: "Student Code", key: "studentCode" },
    { header: "Class", key: "className" },
    { header: "Level", key: "level" },
    { header: "Status", key: "status" },
  ];

  const rows = students.map((s) => ({
    name: s.user?.name ?? "Unknown",
    email: s.user?.email ?? "",
    studentCode: s.studentCode ?? "—",
    className: s.class?.name ?? "—",
    level: s.level?.name ?? "—",
    status: s.status,
  }));

  return { columns, rows };
}
